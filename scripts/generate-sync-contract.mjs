#!/usr/bin/env node
/** Deterministic generation, no network/dependencies. --check never writes. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = p => readFileSync(resolve(root, p), 'utf8');
const schemaText = read('packages/sync-contract/sync.schema.json');
const protocolText = read('packages/sync-contract/protocol.json');
const schema = JSON.parse(schemaText), protocol = JSON.parse(protocolText);
const template = read('packages/sync-contract/templates/client.dart.txt');
const supported = new Set(['$ref', 'type', 'properties', 'required', 'additionalProperties', 'items', 'enum', 'format', 'pattern', 'minLength', 'maxLength', 'minimum']);
function check(s) {
  for (const [key, value] of Object.entries(s)) {
    if (!supported.has(key)) throw new Error(`Extend Dart validator before using schema keyword: ${key}`);
    if (key === 'format' && !['uuid', 'sync-cursor'].includes(value)) throw new Error(`Unsupported format ${value}`);
    if (key === 'type' && (Array.isArray(value) ? value : [value]).some(t => !['null', 'string', 'integer', 'object', 'array'].includes(t))) throw new Error(`Unsupported type ${value}`);
    if (key === 'additionalProperties' && typeof value !== 'boolean') throw new Error('Schema-valued additionalProperties unsupported');
    if (key === 'properties') Object.values(value).forEach(check);
    if (key === 'items') check(value);
    if (key === '$ref' && !schema.definitions[value.replace('#/definitions/', '')]) throw new Error(`Unknown ref ${value}`);
  }
}
Object.values(schema.definitions).forEach(check);
const hash = createHash('sha256').update(schemaText + protocolText + template).digest('hex');
const pattern = schema.definitions.Cursor.pattern;
const methods = Object.entries(protocol.routes).map(([name, r]) => `
  Future<Map<String, dynamic>> ${name}(Map<String, dynamic> data) =>
      _request('${r.method}', '${r.path}', '${r.request}', '${r.response}', data);`).join('\n');
let dart = template;
for (const [key, value] of Object.entries({ HASH: hash, VERSION: protocol.version, MAX: protocol.cursorMaximum, SCHEMA: JSON.stringify(schema), PATTERN: pattern, METHODS: methods })) dart = dart.replaceAll(`__${key}__`, String(value));
const ts = `// GENERATED by scripts/generate-sync-contract.mjs. DO NOT EDIT.
// Source SHA256: ${hash}
export const SYNC_CONTRACT_VERSION = ${protocol.version};
export const SYNC_CURSOR_MAXIMUM = '${protocol.cursorMaximum}';
export function isSyncCursor(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  const match = new RegExp(${JSON.stringify(pattern)}).exec(value);
  return match?.[0] === value && (value.length < SYNC_CURSOR_MAXIMUM.length ||
    (value.length === SYNC_CURSOR_MAXIMUM.length && value <= SYNC_CURSOR_MAXIMUM));
}
`;
const outputs = {
  'apps/api/src/modules/sync/generated/sync-contract.ts': ts,
  'apps/staff-mobile/lib/core/network/generated/sync_wire_client.dart': dart,
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (read(path) !== content) throw new Error(`${path} is stale; run node scripts/generate-sync-contract.mjs`);
  } else {
    mkdirSync(dirname(resolve(root, path)), { recursive: true });
    writeFileSync(resolve(root, path), content);
  }
}
console.log(`✓ sync contract v${protocol.version} generated artifacts ${process.argv.includes('--check') ? 'verified' : 'written'}`);
